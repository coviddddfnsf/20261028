#!/usr/bin/env bash
set -euo pipefail

if [[ $# -eq 6 && ! "${3:-}" =~ ^[0-9]+$ ]]; then
    bench_name=$1
    ckpt_name=$2
    env_cfg_type=$3
    action_type=$4
    seed=$5
    gpu_id=$6
    SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    ROOT_DIR="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
    UTILS_DIR="${ROOT_DIR}/XPolicyLab/utils"
    export CUDA_VISIBLE_DEVICES="${gpu_id}"
    export ACT_ACTION_DIM="$(bash "${UTILS_DIR}/get_action_dim.sh" "${ROOT_DIR}" "${env_cfg_type}")"
    ckpt_setting="${bench_name}-${ckpt_name}-${env_cfg_type}-${action_type}"
    python3 "${SCRIPT_DIR}/imitate_episodes.py" \
        --bench_name "${bench_name}" \
        --task_name "${ckpt_name}" \
        --ckpt_setting "${ckpt_setting}" \
        --ckpt_dir "${SCRIPT_DIR}/checkpoints/${ckpt_setting}-${seed}" \
        --policy_class ACT \
        --kl_weight 10 \
        --chunk_size 50 \
        --hidden_dim 512 \
        --batch_size 16 \
        --dim_feedforward 3200 \
        --num_epochs 2000 \
        --lr 1e-5 \
        --save_freq 2000 \
        --seed "${seed}" \
        --gate_type none
    exit
fi

if [[ $# -lt 6 ]]; then
    echo "Usage: $0 TASK TASK_CONFIG EPISODES SEED GPU_ID EXP_NAME [--gate_type TYPE] [--disable_force] [--num_epochs N] [--batch_size N]" >&2
    exit 2
fi

task_name=$1
task_config=$2
episode_count=$3
seed=$4
gpu_id=$5
experiment_name=$6
shift 6

gate_type=none
disable_force=false
num_epochs=2000
batch_size=16
while (($#)); do
    case "$1" in
        --gate_type)
            gate_type=${2:?--gate_type requires a value}
            shift 2
            ;;
        --disable_force)
            disable_force=true
            shift
            ;;
        --num_epochs)
            num_epochs=${2:?--num_epochs requires a value}
            shift 2
            ;;
        --batch_size)
            batch_size=${2:?--batch_size requires a value}
            shift 2
            ;;
        *)
            echo "Unknown argument: $1" >&2
            exit 2
            ;;
    esac
done

if [[ ! "$episode_count" =~ ^[1-9][0-9]*$ || ! "$num_epochs" =~ ^[1-9][0-9]*$ || ! "$batch_size" =~ ^[1-9][0-9]*$ ]]; then
    echo "Episodes, num_epochs, and batch_size must be positive integers." >&2
    exit 2
fi
micro_batch_size="${batch_size}"
grad_accum_steps=1
case "$gate_type" in
    none|hard|cross_attn|soft) ;;
    *)
        echo "Unsupported gate_type: $gate_type" >&2
        exit 2
        ;;
esac

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
XPL_ROOT="${ROOT_DIR}/XPolicyLab"
UTILS_DIR="${XPL_ROOT}/utils"
embodiment=aloha_agilex
action_type=joint
raw_data_dir="${ROOT_DIR}/data/${task_config}/${task_name}/${embodiment}/data"
processed_dir="${SCRIPT_DIR}/processed_data/${task_config}/${task_name}/${embodiment}-${action_type}"
dataset_setting="${task_config}-${task_name}-${embodiment}-${action_type}"
ckpt_dir="${SCRIPT_DIR}/checkpoints/${experiment_name}"

export CUDA_VISIBLE_DEVICES="${gpu_id}"
action_dim=$(bash "${UTILS_DIR}/get_action_dim.sh" "${ROOT_DIR}" "${embodiment}")
export ACT_ACTION_DIM="${action_dim}"

if [[ ! -d "${raw_data_dir}" ]]; then
    echo "Raw episode directory not found: ${raw_data_dir}" >&2
    exit 1
fi
episode_files=$(find "${raw_data_dir}" -maxdepth 1 -type f -name 'episode_*.hdf5' | wc -l)
if ((episode_files < episode_count)); then
    echo "Expected ${episode_count} episodes in ${raw_data_dir}, found ${episode_files}." >&2
    exit 1
fi

processed_files=0
if [[ -d "${processed_dir}" ]]; then
    processed_files=$(find "${processed_dir}" -maxdepth 1 -type f -name 'episode_*.hdf5' | wc -l)
fi
if ((processed_files != episode_count)); then
    (
        cd "${SCRIPT_DIR}"
        bash process_data.sh "${task_config}" "${task_name}" "${embodiment}" "${action_type}" \
            --episode_num "${episode_count}"
    )
fi

if [[ ! -f "${SCRIPT_DIR}/TASK_CONFIGS.json" ]]; then
    echo "Dataset config was not generated by process_data.sh." >&2
    exit 1
fi

mkdir -p "${ckpt_dir}"
train_args=(
    --bench_name "${task_name}" \
    --task_name "${experiment_name}" \
    --ckpt_setting "${dataset_setting}" \
    --ckpt_dir "${ckpt_dir}" \
    --policy_class ACT \
    --kl_weight 10 \
    --chunk_size 50 \
    --hidden_dim 512 \
    --batch_size "${micro_batch_size}" \
    --grad_accum_steps "${grad_accum_steps}" \
    --dim_feedforward 3200 \
    --num_epochs "${num_epochs}" \
    --lr 1e-5 \
    --save_freq "${num_epochs}" \
    --seed "${seed}" \
    --gate_type "${gate_type}"
)
if [[ "${disable_force}" == true ]]; then
    train_args+=(--disable_force)
fi
python3 imitate_episodes.py "${train_args[@]}"

printf '{"task":"%s","task_config":"%s","episodes":%s,"seed":%s,"gate_type":"%s","disable_force":%s,"num_epochs":%s,"effective_batch_size":%s,"micro_batch_size":%s,"grad_accum_steps":%s}\n' \
    "${task_name}" "${task_config}" "${episode_count}" "${seed}" "${gate_type}" "${disable_force}" "${num_epochs}" "${batch_size}" "${micro_batch_size}" "${grad_accum_steps}" \
    > "${ckpt_dir}/training_config.json"
